//! Data source abstraction.
//!
//! Definitions (rules, groups, tests, configuration entries) are stored
//! through the generic [`Repository`] trait; check executions through
//! [`ExecutionRepository`]. Each category is configured independently
//! ([`DataSourcesConfig`]) and may use a different backend:
//!
//! * `memory` — non-persistent, for development and tests;
//! * `json` / `yaml` — one file holding a list per category (several
//!   categories may share a file, each under its own section); for executions
//!   the path is a directory with one file per execution;
//! * `postgres` — one table per category (feature `postgres`).

pub mod file;
pub mod memory;
#[cfg(feature = "postgres")]
pub mod postgres;

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::Arc;

use async_trait::async_trait;
use chrono::{DateTime, Utc};
use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::model::{ConfigEntry, Execution, ExecutionError, Rule, RuleGroup, TestCase};

#[derive(Debug, thiserror::Error)]
pub enum StoreError {
    #[error("{kind} '{id}' was not found")]
    NotFound { kind: &'static str, id: String },
    #[error("{kind} '{id}' already exists")]
    Conflict { kind: &'static str, id: String },
    #[error("I/O error on {path}: {message}")]
    Io { path: String, message: String },
    #[error("invalid data in {location}: {message}")]
    Format { location: String, message: String },
    #[error("database error: {0}")]
    Database(String),
    #[error("{0}")]
    Unsupported(String),
}

/// A persisted definition identified by a unique key.
pub trait Definition: Clone + PartialEq + Serialize + DeserializeOwned + Send + Sync + 'static {
    /// Singular name used in messages ("rule").
    const KIND: &'static str;
    /// Category name, also the default file section ("rules").
    const CATEGORY: &'static str;
    fn key(&self) -> &str;
}

impl Definition for Rule {
    const KIND: &'static str = "rule";
    const CATEGORY: &'static str = "rules";
    fn key(&self) -> &str {
        &self.id
    }
}

impl Definition for RuleGroup {
    const KIND: &'static str = "rule group";
    const CATEGORY: &'static str = "groups";
    fn key(&self) -> &str {
        &self.name
    }
}

impl Definition for TestCase {
    const KIND: &'static str = "test";
    const CATEGORY: &'static str = "tests";
    fn key(&self) -> &str {
        &self.id
    }
}

impl Definition for ConfigEntry {
    const KIND: &'static str = "configuration entry";
    const CATEGORY: &'static str = "config";
    fn key(&self) -> &str {
        &self.key
    }
}

/// Storage of one category of definitions.
#[async_trait]
pub trait Repository<T: Definition>: Send + Sync {
    /// All definitions, sorted by key.
    async fn list(&self) -> Result<Vec<T>, StoreError>;
    async fn get(&self, key: &str) -> Result<Option<T>, StoreError>;
    /// Fails with `Conflict` if the key exists.
    async fn create(&self, item: &T) -> Result<(), StoreError>;
    /// Fails with `NotFound` if the key does not exist.
    async fn update(&self, item: &T) -> Result<(), StoreError>;
    /// Fails with `NotFound` if the key does not exist.
    async fn delete(&self, key: &str) -> Result<(), StoreError>;
    /// Cheap change indicator used by polling; `None` when the backend has
    /// none, in which case polling reloads the definitions.
    async fn fingerprint(&self) -> Result<Option<String>, StoreError> {
        Ok(None)
    }
    /// Human-readable description of the backend ("yaml file data/rules.yaml").
    fn describe(&self) -> String;
}

/// Storage of check executions.
///
/// Executions are identified by UUIDs generated by Drover; `insert` never
/// overwrites an existing execution and each execution is only updated by the
/// task that owns it.
#[async_trait]
pub trait ExecutionRepository: Send + Sync {
    /// Fails with `Conflict` if the id exists.
    async fn insert(&self, execution: &Execution) -> Result<(), StoreError>;
    /// Replaces the stored execution; fails with `NotFound` if it does not exist.
    async fn update(&self, execution: &Execution) -> Result<(), StoreError>;
    async fn get(&self, id: Uuid) -> Result<Option<Execution>, StoreError>;
    /// Marks every pending or running execution as failed (startup recovery).
    async fn fail_unfinished(&self, error: &ExecutionError, now: DateTime<Utc>) -> Result<u64, StoreError>;
    /// Deletes terminal executions finished before `cutoff`.
    async fn purge_finished_before(&self, cutoff: DateTime<Utc>) -> Result<u64, StoreError>;
    fn describe(&self) -> String;
}

/// Marks an unfinished execution as failed (shared by backends).
pub(crate) fn fail_execution(execution: &mut Execution, error: &ExecutionError, now: DateTime<Utc>) {
    execution.status = crate::model::ExecutionStatus::Failed;
    execution.finished_at = Some(now);
    execution.error = Some(error.clone());
}

fn default_true() -> bool {
    true
}

fn default_max_connections() -> u32 {
    5
}

fn default_connect_timeout() -> u64 {
    10
}

/// Configuration of one data source.
#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
#[serde(tag = "type", rename_all = "lowercase", deny_unknown_fields)]
pub enum DataSourceConfig {
    Memory,
    Json {
        path: PathBuf,
        #[serde(default)]
        section: Option<String>,
    },
    Yaml {
        path: PathBuf,
        #[serde(default)]
        section: Option<String>,
    },
    Postgres {
        url: String,
        /// Table name, optionally schema-qualified. Defaults to `drover_<category>`.
        #[serde(default)]
        table: Option<String>,
        #[serde(default = "default_max_connections")]
        max_connections: u32,
        /// Seconds to wait for a connection (startup fails after this).
        #[serde(default = "default_connect_timeout")]
        connect_timeout_secs: u64,
        /// Create missing tables at startup.
        #[serde(default = "default_true")]
        auto_migrate: bool,
    },
}

impl DataSourceConfig {
    pub fn kind(&self) -> &'static str {
        match self {
            DataSourceConfig::Memory => "memory",
            DataSourceConfig::Json { .. } => "json",
            DataSourceConfig::Yaml { .. } => "yaml",
            DataSourceConfig::Postgres { .. } => "postgres",
        }
    }
}

/// Data sources of every category.
#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct DataSourcesConfig {
    pub rules: DataSourceConfig,
    pub groups: DataSourceConfig,
    pub tests: DataSourceConfig,
    pub config: DataSourceConfig,
    pub executions: DataSourceConfig,
}

impl DataSourcesConfig {
    pub fn memory() -> Self {
        DataSourcesConfig {
            rules: DataSourceConfig::Memory,
            groups: DataSourceConfig::Memory,
            tests: DataSourceConfig::Memory,
            config: DataSourceConfig::Memory,
            executions: DataSourceConfig::Memory,
        }
    }
}

/// The opened repositories.
#[derive(Clone)]
pub struct Stores {
    pub rules: Arc<dyn Repository<Rule>>,
    pub groups: Arc<dyn Repository<RuleGroup>>,
    pub tests: Arc<dyn Repository<TestCase>>,
    pub config: Arc<dyn Repository<ConfigEntry>>,
    pub executions: Arc<dyn ExecutionRepository>,
}

impl Stores {
    pub fn memory() -> Self {
        Stores {
            rules: Arc::new(memory::MemoryRepository::default()),
            groups: Arc::new(memory::MemoryRepository::default()),
            tests: Arc::new(memory::MemoryRepository::default()),
            config: Arc::new(memory::MemoryRepository::default()),
            executions: Arc::new(memory::MemoryExecutions::default()),
        }
    }

    /// Opens every configured data source. Fails if any mandatory data source
    /// is unavailable (e.g. the database cannot be reached).
    pub async fn open(config: &DataSourcesConfig) -> Result<Stores, crate::Error> {
        let mut opener = Opener::default();
        Ok(Stores {
            rules: opener.definitions::<Rule>(&config.rules).await?,
            groups: opener.definitions::<RuleGroup>(&config.groups).await?,
            tests: opener.definitions::<TestCase>(&config.tests).await?,
            config: opener.definitions::<ConfigEntry>(&config.config).await?,
            executions: opener.executions(&config.executions).await?,
        })
    }

    pub fn describe(&self) -> serde_json::Value {
        serde_json::json!({
            "rules": self.rules.describe(),
            "groups": self.groups.describe(),
            "tests": self.tests.describe(),
            "config": self.config.describe(),
            "executions": self.executions.describe(),
        })
    }
}

/// Opens data sources, sharing file locks and connection pools between
/// categories that use the same file or database.
#[derive(Default)]
struct Opener {
    files: HashMap<PathBuf, Arc<file::FileDocument>>,
    #[cfg(feature = "postgres")]
    pools: HashMap<String, sqlx::PgPool>,
}

fn invalid(category: &str, message: impl std::fmt::Display) -> crate::Error {
    crate::Error::ConfigValidation(format!("data source '{category}': {message}"))
}

impl Opener {
    fn document(&mut self, path: &PathBuf, format: file::Format) -> Arc<file::FileDocument> {
        let key = std::path::absolute(path).unwrap_or_else(|_| path.clone());
        self.files
            .entry(key)
            .or_insert_with(|| Arc::new(file::FileDocument::new(path.clone(), format)))
            .clone()
    }

    async fn definitions<T>(
        &mut self,
        config: &DataSourceConfig,
    ) -> Result<Arc<dyn Repository<T>>, crate::Error>
    where
        T: Backed,
    {
        Ok(match config {
            DataSourceConfig::Memory => Arc::new(memory::MemoryRepository::<T>::default()),
            DataSourceConfig::Json { path, section } | DataSourceConfig::Yaml { path, section } => {
                let format = file::Format::of(config);
                let doc = self.document(path, format);
                let section = section.clone().unwrap_or_else(|| T::CATEGORY.to_string());
                Arc::new(file::FileRepository::<T>::new(doc, section))
            }
            DataSourceConfig::Postgres { .. } => self.postgres_definitions::<T>(config).await?,
        })
    }

    #[cfg(feature = "postgres")]
    async fn pool(
        &mut self,
        category: &str,
        config: &DataSourceConfig,
    ) -> Result<sqlx::PgPool, crate::Error> {
        let DataSourceConfig::Postgres {
            url,
            max_connections,
            connect_timeout_secs,
            ..
        } = config
        else {
            unreachable!()
        };
        if let Some(pool) = self.pools.get(url) {
            return Ok(pool.clone());
        }
        let timeout = std::time::Duration::from_secs((*connect_timeout_secs).max(1));
        let pool = postgres::connect(url, *max_connections, timeout)
            .await
            .map_err(|e| invalid(category, format!("cannot connect to PostgreSQL: {e}")))?;
        self.pools.insert(url.clone(), pool.clone());
        Ok(pool)
    }

    #[cfg(feature = "postgres")]
    async fn postgres_definitions<T: Backed>(
        &mut self,
        config: &DataSourceConfig,
    ) -> Result<Arc<dyn Repository<T>>, crate::Error> {
        let DataSourceConfig::Postgres {
            table, auto_migrate, ..
        } = config
        else {
            unreachable!()
        };
        let pool = self.pool(T::CATEGORY, config).await?;
        let table = table.clone().unwrap_or_else(|| format!("drover_{}", T::CATEGORY));
        postgres::open_repository::<T>(pool, &table, *auto_migrate)
            .await
            .map_err(|e| invalid(T::CATEGORY, e))
    }

    #[cfg(not(feature = "postgres"))]
    async fn postgres_definitions<T: Backed>(
        &mut self,
        _config: &DataSourceConfig,
    ) -> Result<Arc<dyn Repository<T>>, crate::Error> {
        Err(invalid(
            T::CATEGORY,
            "Drover was built without the `postgres` feature",
        ))
    }

    async fn executions(
        &mut self,
        config: &DataSourceConfig,
    ) -> Result<Arc<dyn ExecutionRepository>, crate::Error> {
        Ok(match config {
            DataSourceConfig::Memory => Arc::new(memory::MemoryExecutions::default()),
            DataSourceConfig::Json { path, section } | DataSourceConfig::Yaml { path, section } => {
                if section.is_some() {
                    return Err(invalid(
                        "executions",
                        "`section` is not supported: executions are stored one file per execution in the `path` directory",
                    ));
                }
                let store = file::FileExecutions::open(path.clone(), file::Format::of(config))
                    .await
                    .map_err(|e| invalid("executions", e))?;
                Arc::new(store)
            }
            #[cfg(feature = "postgres")]
            DataSourceConfig::Postgres {
                table, auto_migrate, ..
            } => {
                let pool = self.pool("executions", config).await?;
                let table = table.clone().unwrap_or_else(|| "drover_executions".to_string());
                Arc::new(
                    postgres::PgExecutions::open(pool, &table, *auto_migrate)
                        .await
                        .map_err(|e| invalid("executions", e))?,
                )
            }
            #[cfg(not(feature = "postgres"))]
            DataSourceConfig::Postgres { .. } => {
                return Err(invalid(
                    "executions",
                    "Drover was built without the `postgres` feature",
                ));
            }
        })
    }
}

/// A definition that every compiled-in backend can store.
#[cfg(feature = "postgres")]
pub trait Backed: Definition + postgres::PgEntity {}
#[cfg(feature = "postgres")]
impl<T: Definition + postgres::PgEntity> Backed for T {}

/// A definition that every compiled-in backend can store.
#[cfg(not(feature = "postgres"))]
pub trait Backed: Definition {}
#[cfg(not(feature = "postgres"))]
impl<T: Definition> Backed for T {}
